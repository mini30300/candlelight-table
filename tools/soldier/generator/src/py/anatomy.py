def _E(bone, c, r, rot=None, **kw):
    return Prim("ellipsoid", bone, c=np.asarray(c, float), r=np.asarray(r, float),
                rot=np.eye(3) if rot is None else np.asarray(rot, float), **kw)


def _C(bone, a, b, ra, rb=None, **kw):
    return Prim("capsule", bone, a=np.asarray(a, float), b=np.asarray(b, float), ra=ra,
                rb=ra if rb is None else rb, **kw)


def _T(bone, pts, r, scale=None, **kw):
    pts = np.asarray(pts, float)
    r = np.broadcast_to(np.asarray(r, float), (len(pts),)).copy()
    if scale is not None:
        kw["scale"] = list(scale)
    return Prim("tube", bone, pts=pts, r=r, **kw)


def _LO(bone, sec, **kw):
    return Prim("loft", bone, sec=np.asarray(sec, float), **kw)


def _RB(bone, c, e, rnd, rot=None, **kw):
    return Prim("rbox", bone, c=np.asarray(c, float), e=np.asarray(e, float), round=rnd,
                rot=np.eye(3) if rot is None else np.asarray(rot, float), **kw)


def _lid(bone, c, r, t, n, y_front, side, **kw):
    """เปลือกตาบน (side +1) / ล่าง (-1): ขอบเปลือกตาผ่านจุดหน้าสุดของลูกตาที่ระดับ y_front (เทียบศูนย์ลูกตา)"""
    n = np.asarray(n, float)
    n = n / np.linalg.norm(n)
    qf = np.array([0.0, y_front, np.sqrt(max(r * r - y_front * y_front, 0.0))])
    return Prim("lid", bone, c=np.asarray(c, float), r=r, t=t, n=n, off=float(qf @ n), side=side, **kw)


def mirror_prim(p):
    q = dict(p.p)
    if "n" in q:
        q["n"] = q["n"] * np.array([-1, 1, 1.0])
    for key in ("c", "a", "b"):
        if key in q:
            q[key] = q[key] * np.array([-1, 1, 1.0])
    if "pts" in q:
        q["pts"] = q["pts"] * np.array([-1, 1, 1.0])
    if "rot" in q:
        q["rot"] = MX @ q["rot"] @ MX
    if "sx" in q:
        q["sx"] = -q["sx"]
    if "sec" in q:
        q.pop("_tab", None)
    kind = p.kind
    m = Prim(kind, mirror_name(p.bone), outset=p.outset, tag=p.tag, name=_mname(p.name), neg=p.neg, k=p.k,
             weights=_mweights(p.weights), **q)
    return m


def _mname(n):
    return n[:-2] + "_R" if n.endswith("_L") else n


def _mweights(w):
    if w is None:
        return None
    if isinstance(w, dict):
        return {mirror_name(b): v for b, v in w.items()}
    return [(y, {mirror_name(b): v for b, v in d.items()}) for y, d in w]


def both(prims):
    """ชิ้นข้างซ้าย -> ซ้าย+ขวา ; ชิ้นกลางลำตัว (ชื่อไม่ลงท้าย _L) คงไว้ชิ้นเดียว"""
    out = []
    for p in prims:
        out.append(p)
        if p.name.endswith("_L"):
            out.append(mirror_prim(p))
    return out


