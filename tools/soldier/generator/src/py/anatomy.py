def _arc(y0, z0, half=0.026, back=0.013, lift=0.0008, n=9):
    """เส้นโค้งตามแนวฟัน (ปาก): มุมปากถอยไปหลัง back และยกขึ้น lift"""
    xs = np.linspace(-half, half, n)
    u = (xs / half) ** 2
    return np.stack([xs, y0 + lift * u, z0 - back * u], 1)


